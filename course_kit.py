class _Exec:
    def __init__(self, data):
        self._data = data

    def execute(self):
        return self._data


class FakeGmailService:
    """Supports: service.users().messages().list/get(...).execute()
                 service.users().drafts().create(...).execute()"""

    def __init__(self, messages=None):
        self.messages_store = messages or {}
        self.created_drafts = []
        self.last_list_kwargs = {}

    def users(self):
        return self

    def messages(self):
        return self

    def drafts(self):
        return self

    def list(self, userId="me", **kwargs):
        self.last_list_kwargs = kwargs
        ids = list(self.messages_store)
        n = kwargs.get("maxResults") or len(ids)
        return _Exec({"messages": [{"id": i} for i in ids[:n]],
                      "resultSizeEstimate": len(ids)})

    def get(self, userId="me", id=None, **kwargs):
        if id not in self.messages_store:
            raise KeyError(f"no such message id: {id}")
        data = dict(self.messages_store[id])
        data["id"] = id
        return _Exec(data)

    def create(self, userId="me", body=None, **kwargs):
        self.created_drafts.append(body)
        return _Exec({"id": f"draft_{len(self.created_drafts)}",
                      "message": {"id": f"m_draft_{len(self.created_drafts)}"}})


