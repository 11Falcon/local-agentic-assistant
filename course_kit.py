class FakeToolCall:
    """Looks like an OpenAI SDK tool call: .id, .function.name, .function.arguments."""

    def __init__(self, name, arguments, call_id="call_1"):
        self.id = call_id
        self.type = "function"
        if not isinstance(arguments, str):
            arguments = json.dumps(arguments)
        self.function = SimpleNamespace(name=name, arguments=arguments)


class FakeMessage:
    def __init__(self, content=None, tool_calls=None):
        self.role = "assistant"
        self.content = content
        self.tool_calls = tool_calls


class FakeLLM:
    """Scriptable stand-in for openai.OpenAI().

    fake = FakeLLM(["hello", FakeMessage(tool_calls=[FakeToolCall("f", "{}")])])
    Each .chat.completions.create(...) call pops the next scripted response and
    records its kwargs in fake.calls.
    """

    def __init__(self, responses):
        self._responses = list(responses)
        self.calls = []
        self.embed_calls = []
        self.chat = SimpleNamespace(completions=SimpleNamespace(create=self._create))
        self.embeddings = SimpleNamespace(create=self._embed)

    def _embed(self, model=None, input=None, **kwargs):
        return _embed_response(self.embed_calls, model, input)

    def _create(self, **kwargs):
        recorded = dict(kwargs)
        if isinstance(kwargs.get("messages"), list):
            # snapshot: agents mutate their messages list after the call
            recorded["messages"] = list(kwargs["messages"])
        self.calls.append(recorded)
        if not self._responses:
            raise AssertionError(
                "FakeLLM ran out of scripted responses - your code called the "
                "model more times than this check expects."
            )
        resp = self._responses.pop(0)
        message = FakeMessage(content=resp) if isinstance(resp, str) else resp
        if kwargs.get("stream"):
            text = message.content or ""
            chunks = [
                SimpleNamespace(choices=[SimpleNamespace(
                    delta=SimpleNamespace(content=text[i:i + 4]), finish_reason=None)])
                for i in range(0, len(text), 4)
            ]
            chunks.append(SimpleNamespace(choices=[SimpleNamespace(
                delta=SimpleNamespace(content=None), finish_reason="stop")]))
            return iter(chunks)
        finish = "tool_calls" if message.tool_calls else "stop"
        return SimpleNamespace(choices=[SimpleNamespace(message=message, finish_reason=finish)])


# --------------------------------------------------------------------------
# Fake embeddings (deterministic bag-of-words, so "similar" really is similar)
# --------------------------------------------------------------------------

_VOCAB = ["python", "agent", "calendar", "email", "model", "tool", "meeting",
          "vector", "loop", "event"]


def _bow_vector(text):
    """A tiny deterministic 'embedding': how often each vocab term appears,
    plus a length feature so no vector is ever all zeros."""
    words = str(text).lower().split()
    vec = [float(sum(1 for w in words if term in w)) for term in _VOCAB]
    vec.append(len(words) / 100.0)
    return vec


def _embed_response(log, model, input):
    if isinstance(input, str):
        input = [input]
    input = list(input or [])
    log.append({"model": model, "input": input})
    data = [SimpleNamespace(embedding=_bow_vector(t), index=i)
            for i, t in enumerate(input)]
    return SimpleNamespace(data=data, model=model)


class FakeEmbedder:
    """Scriptless stand-in for a client used only for embeddings.

    fake = FakeEmbedder()
    fake.embeddings.create(model="m", input=["a", "b"]).data[0].embedding
    Every call is recorded in fake.calls.
    """

    def __init__(self):
        self.calls = []
        self.embeddings = SimpleNamespace(create=self._create)

    def _create(self, model=None, input=None, **kwargs):
        return _embed_response(self.calls, model, input)


