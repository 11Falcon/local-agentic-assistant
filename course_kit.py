class FakeSlackClient:
    def __init__(self, history=None):
        # newest-first, exactly like the real conversations.history API
        self.history = history or []
        self.posted = []

    def chat_postMessage(self, channel=None, text=None, **kwargs):
        self.posted.append({"channel": channel, "text": text})
        return {"ok": True, "channel": channel,
                "ts": f"171000000{len(self.posted)}.000100"}

    def conversations_history(self, channel=None, limit=10, **kwargs):
        return {"ok": True, "messages": self.history[:limit]}


