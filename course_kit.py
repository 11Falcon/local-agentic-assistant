class FakeCalendarService:
    """Supports: service.events().list/insert(...).execute()"""

    def __init__(self, events=None):
        self.events_store = events or []
        self.inserted = []
        self.last_list_kwargs = {}

    def events(self):
        return self

    def list(self, calendarId="primary", **kwargs):
        self.last_list_kwargs = kwargs
        n = kwargs.get("maxResults") or len(self.events_store)
        return _Exec({"items": self.events_store[:n]})

    def insert(self, calendarId="primary", body=None, **kwargs):
        self.inserted.append(body)
        return _Exec({"id": f"evt_{len(self.inserted)}",
                      "htmlLink": "https://calendar.google.com/event?eid=fake"})


