def load_task(module_dir: str, filename: str):
    """Import a task file, e.g. load_task('0x00-environment_setup', '1-hello_qwen.py')."""
    import pytest
    path = COURSE_ROOT / module_dir / filename
    if not path.exists():
        pytest.fail(f"Missing file: {module_dir}/{filename} - create it, then re-run the checker.")
    mod_dir = str(path.parent)
    if mod_dir not in sys.path:            # lets task files do __import__('1-other_task')
        sys.path.insert(0, mod_dir)
    name = filename[:-3]
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(mod)
    except Exception as exc:  # noqa: BLE001 - report any student-code crash
        pytest.fail(f"{module_dir}/{filename} crashed on import: {exc!r}")
    sys.modules[name] = mod
    return mod


def import_or_fail(module_name: str, hint: str):
    """Import a package module (core.agent, agents.gmail_agent, ...) with a friendly error."""
    import pytest
    try:
        return importlib.import_module(module_name)
    except Exception as exc:  # noqa: BLE001
        pytest.fail(f"Could not import '{module_name}': {exc!r}\nHint: {hint}")


